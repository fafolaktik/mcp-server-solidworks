"""check_contract with cadcritic 1.1 (hole/boss descriptors carry `area`) — runs WITHOUT SolidWorks.

Recorded 2026-10-16 live (SOLIDWORKS 2026 SP4, cadcritic 1.1.0): two STEP parts generated by
fixtures/check_contract_v11/make_parts.py (build123d), imported into SolidWorks with
open_document, then check_contract — capturing exactly what it consumed:
  <part>.faces.json      raw ExecutionResponse of analyze_model(faces)
  <part>.cadcritic.json  argv / exit_code / stdout / stderr of `cadcritic check`
  <part>.contract.json   the contract
  bore_interrupted  a D8 bore along X interrupted by a slot: TWO coaxial equal-radius holes
                    (25 mm / 15 mm long). SolidWorks faces 0 (377 mm2) and 6 (628 mm2) each pass
                    the geometric test for BOTH holes -> the area tie-break settles the tie.
  hole_split        ONE vertical D8 hole whose wall is TWO half-cylinder faces (0 and 4,
                    126 mm2 each) -> mapped to both by SUMMED area.
"""
import copy
import json
import os
import subprocess
import sys

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
_ADAPTER_DIR = os.path.dirname(_HERE)
_FIX = os.path.join(_HERE, "fixtures", "check_contract_v11")
sys.path.insert(0, _ADAPTER_DIR)

import contract_check  # noqa: E402
import server          # noqa: E402


def _load(name):
    with open(os.path.join(_FIX, name), encoding="utf-8") as fh:
        return json.load(fh)


def _faces(part):
    return json.loads(_load(f"{part}.faces.json")["cadState"]["features"][0])["faces"]


def _report(part):
    rec = _load(f"{part}.cadcritic.json")
    assert rec["exit_code"] == 0
    return json.loads(rec["stdout"])


def _features(out):
    return {d["id"]: d for req in out["requirements"] for d in req["features"]}


def test_recordings_are_cadcritic_1_1_with_hole_area():
    for part in ("bore_interrupted", "hole_split"):
        for d in _features(_report(part)).values():
            assert d["type"] == "hole" and d["units"]["area"] == "mm2" and d["area"] > 0


# ---------------------------------------------------------------------------
# (a) interrupted bore: area settles a hole tie
# ---------------------------------------------------------------------------
def test_hole_tie_settled_by_area():
    out = contract_check.annotate_report(_report("bore_interrupted"), _faces("bore_interrupted"))
    feats = _features(out)
    left, right = feats["hole:-17.500,10.000,10.000"], feats["hole:22.500,10.000,10.000"]
    for d in (left, right):
        assert d["face_match"]["geometric_candidates"] == [0, 6]      # a genuine tie geometrically
        assert d["face_match"]["resolved_by"] == "area"
    assert (left["face_index"], left["face_indices"]) == (6, [6])     # 25 mm segment, 628 mm2
    assert (right["face_index"], right["face_indices"]) == (0, [0])   # 15 mm segment, 377 mm2
    assert out["face_mapping"]["multiple"] == [] and out["face_mapping"]["unmatched"] == []


def test_hole_tie_without_area_stays_multiple():
    report = _report("bore_interrupted")
    for req in report["requirements"]:
        for d in req["features"]:
            d.pop("area")                                             # what cadcritic 1.0 sent
    out = contract_check.annotate_report(report, _faces("bore_interrupted"))
    assert {e["id"] for e in out["face_mapping"]["multiple"]} == {
        "hole:-17.500,10.000,10.000", "hole:22.500,10.000,10.000"}
    assert all("no area" in e["reason"] for e in out["face_mapping"]["multiple"])


# ---------------------------------------------------------------------------
# (b) split wall: one hole, two faces, summed area
# ---------------------------------------------------------------------------
def test_split_hole_wall_maps_to_all_its_faces():
    out = contract_check.annotate_report(_report("hole_split"), _faces("hole_split"))
    (d,) = _features(out).values()
    assert d["face_indices"] == [0, 4]
    assert d["face_index"] == 0
    assert d["face_match"] == {"status": "matched", "candidates": [0, 4], "resolved_by": "area",
                               "geometric_candidates": [0, 4]}
    face_area = {f["i"]: f["area"] for f in _faces("hole_split")}
    assert face_area[0] + face_area[4] == pytest.approx(d["area"] * 1e-6, abs=2e-6)
    assert out["face_mapping"]["matched"] == 1 and out["face_mapping"]["multiple"] == []


def test_split_hole_ambiguous_sets_are_reported_not_guessed():
    faces = _faces("hole_split")
    extra = copy.deepcopy(next(f for f in faces if f["i"] == 4))
    extra["i"] = 99                       # a third coaxial half-wall: {0,4}, {0,99}, {4,99} all fit
    faces.append(extra)
    out = contract_check.annotate_report(_report("hole_split"), faces)
    (d,) = _features(out).values()
    assert d["face_index"] is None and d["face_indices"] == []
    assert d["face_match"]["status"] == "multiple"
    assert d["face_match"]["area_sets"] == [[0, 4], [0, 99], [4, 99]]


def test_split_hole_summed_area_tolerance_grows_per_face():
    # tolerance = 1e-6 m2 PER FACE summed: 2 mm2 for a two-face wall, measured against the
    # SUM of the recorded (rounded) face areas — 126 + 126 = 252 mm2 here
    face_sum_mm2 = sum(f["area"] for f in _faces("hole_split") if f["i"] in (0, 4)) * 1e6
    report = _report("hole_split")
    d = report["requirements"][0]["features"][0]
    d["area"] = face_sum_mm2 + 1.9         # 1.9 mm2 off: inside 2 x 1 mm2
    out = contract_check.annotate_report(report, _faces("hole_split"))
    assert out["requirements"][0]["features"][0]["face_indices"] == [0, 4]
    d["area"] = face_sum_mm2 + 2.1         # 2.1 mm2 off: outside
    out = contract_check.annotate_report(report, _faces("hole_split"))
    assert out["requirements"][0]["features"][0]["face_match"]["status"] == "multiple"


def test_tool_reports_every_face_of_a_split_wall(monkeypatch, tmp_path):
    rec = _load("hole_split.cadcritic.json")
    faces_resp = _load("hole_split.faces.json")

    def fake_call_raw(tool, params):
        if tool == "export_document":
            with open(params["file_path"], "w") as fh:
                fh.write("ISO-10303-21;\n")
            return {"status": "COMPLETED", "cadState": {}}
        if tool == "analyze_model":
            return faces_resp
        raise AssertionError(tool)

    exe = tmp_path / "cadcritic.exe"
    exe.write_text("")
    monkeypatch.setattr(server, "_call_raw", fake_call_raw)
    monkeypatch.setattr(server, "CADCRITIC_EXE", str(exe))
    monkeypatch.setattr(server, "_log", lambda msg: None)
    monkeypatch.setattr(contract_check.subprocess, "run", lambda argv, **kw: subprocess.CompletedProcess(
        argv, rec["exit_code"], rec["stdout"].encode(), rec["stderr"].encode()))
    out = json.loads(server.check_contract(os.path.join(_FIX, "hole_split.contract.json")))
    d = out["requirements"][0]["features"][0]
    assert (d["face_index"], d["face_indices"]) == (0, [0, 4])
    assert out["score"] == [0, 0.0]
